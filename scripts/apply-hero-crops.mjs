#!/usr/bin/env node
import { access, readFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import {
  cropItems,
  isRecord,
  printCropSummary,
  readGeneratedRecords,
  validateCropRecord,
  validateTransform
} from './lib/crop-import.mjs'
import { atomicWrite, isMain, recordChanges } from './lib/file-operations.mjs'

const defaultRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const schemaVersion = 1
const fallback = { x: 50, y: 50, zoom: 1 }

/** Validate the whole batch before touching the production bridge. */
export async function applyHeroCrops(
  input,
  { projectRoot = defaultRoot, dryRun = false, allowEmpty = false } = {}
) {
  const items = cropItems(input, 'home-hero', schemaVersion)
  const candidates = Object.entries(items).map(([filename, candidate]) => {
    validateCropRecord(candidate, filename, schemaVersion)
    // Legacy compatibility requires actual Hero transforms, not just missing flags.
    const desktop = validateTransform(candidate.desktop, `${filename}.desktop`)
    const mobile = validateTransform(candidate.mobile, `${filename}.mobile`)
    if (
      candidate.confirmed !== undefined &&
      (!isRecord(candidate.confirmed) ||
        ['desktop', 'mobile'].some(
          (key) =>
            candidate.confirmed[key] !== undefined && typeof candidate.confirmed[key] !== 'boolean'
        ))
    )
      throw new Error(`${filename}.confirmed 必须包含布尔确认值。`)
    const confirmed = candidate.confirmed ?? { desktop: true, mobile: true }
    return { filename, candidate, desktop, mobile, confirmed }
  })
  const outputPath = resolve(projectRoot, 'src/data/hero-crop-selections.generated.ts')
  const previous = await readGeneratedRecords(outputPath, 'heroCropSelectionsGenerated')
  const records = { ...previous }
  const skipped = []
  for (const { filename, candidate, desktop, mobile, confirmed } of candidates) {
    if (!confirmed.desktop && !confirmed.mobile) {
      skipped.push(`${filename}: 未确认，保留现有生产配置`)
      continue
    }
    try {
      await access(resolve(projectRoot, 'public/images/home-media', filename))
    } catch (error) {
      if (error.code !== 'ENOENT') throw error
      throw new Error(`${filename}: 找不到对应 WebP 素材；未写入配置。`)
    }
    records[filename] = {
      filename,
      desktop: confirmed.desktop ? desktop : (previous[filename]?.desktop ?? fallback),
      mobile: confirmed.mobile ? mobile : (previous[filename]?.mobile ?? fallback),
      schemaVersion,
      ...(typeof candidate.updatedAt === 'string'
        ? { updatedAt: candidate.updatedAt }
        : previous[filename]?.updatedAt
          ? { updatedAt: previous[filename].updatedAt }
          : {})
    }
  }
  if (!Object.keys(records).length && !allowEmpty)
    throw new Error('没有可应用的 Hero 记录；未写入文件。')
  const summary = recordChanges(previous, records)
  const source = `/** Generated by scripts/apply-hero-crops.mjs. Do not edit by hand. */\nimport type { HeroCropRecord } from '@/lib/hero-crop/types'\n\nexport const heroCropSelectionsGenerated: Readonly<Record<string, HeroCropRecord>> = ${JSON.stringify(records, null, 2)}\n`
  if (!dryRun) await atomicWrite(outputPath, source)
  return { records, summary, skipped, outputPath }
}

if (isMain(import.meta.url)) {
  try {
    const args = process.argv.slice(2).filter((arg) => arg !== '--')
    const path = args.find((arg) => !arg.startsWith('-'))
    if (
      !path ||
      args.some((arg) => arg.startsWith('-') && !['--dry-run', '--allow-empty'].includes(arg))
    )
      throw new Error(
        'Usage: node scripts/apply-hero-crops.mjs <editor-json> [--dry-run] [--allow-empty]'
      )
    const dryRun = args.includes('--dry-run')
    const result = await applyHeroCrops(JSON.parse(await readFile(resolve(path), 'utf8')), {
      dryRun,
      allowEmpty: args.includes('--allow-empty')
    })
    printCropSummary(result.summary, result.skipped, dryRun)
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}
