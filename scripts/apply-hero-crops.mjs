#!/usr/bin/env node

/**
 * Apply an exported Hero crop editor JSON file to the checked-in bridge.
 * Only focal metadata is written; source images and card crop decisions are
 * never changed.
 *
 * Usage:
 *   bun scripts/apply-hero-crops.mjs path/to/hero-crop-editor-v1.json --dry-run
 *   bun scripts/apply-hero-crops.mjs path/to/hero-crop-editor-v1.json
 */
import { access, readFile, writeFile } from 'node:fs/promises'
import { basename, dirname, resolve, sep } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const mediaRoot = resolve(projectRoot, 'public', 'images', 'home-media')
const outputPath = resolve(projectRoot, 'src', 'data', 'hero-crop-selections.generated.ts')
const schemaVersion = 1
const args = process.argv.slice(2)
const inputPath = args.find((arg) => !arg.startsWith('-'))
const dryRun = args.includes('--dry-run')
const allowEmpty = args.includes('--allow-empty')

if (!inputPath) {
  console.error('Usage: bun scripts/apply-hero-crops.mjs <editor-json> [--dry-run]')
  process.exitCode = 1
  process.exit()
}

const clamp = (value, min, max) => Math.min(max, Math.max(min, value))
const numberOr = (value, fallback) => (Number.isFinite(Number(value)) ? Number(value) : fallback)
const normalizeTransform = (value) => ({
  x: clamp(numberOr(value?.x, 50), 0, 100),
  y: clamp(numberOr(value?.y, 50), 0, 100),
  zoom: clamp(numberOr(value?.zoom, 1), 1, 4)
})

const safeFilename = (value) => {
  const raw = String(value)
  const file = basename(raw)
  if (!file || /[\\/]/.test(raw) || file !== raw) return undefined
  return file
}

const readExistingRecords = async () => {
  try {
    const source = await readFile(outputPath, 'utf8')
    const match = source.match(/heroCropSelectionsGenerated[^=]*=\s*(\{[\s\S]*\})\s*$/)
    if (!match) return {}
    const parsed = JSON.parse(match[1])
    return parsed && typeof parsed === 'object' && !Array.isArray(parsed) ? parsed : {}
  } catch {
    return {}
  }
}

const input = JSON.parse(await readFile(resolve(process.cwd(), inputPath), 'utf8'))
const items = input?.items ?? input?.records ?? input
if (!items || typeof items !== 'object' || Array.isArray(items)) {
  console.error('输入文件没有找到 items/records 对象。')
  process.exitCode = 1
  process.exit()
}

// An editor export normally contains every catalog item.  Merging with the
// checked-in bridge also makes partial exports safe: an unconfirmed item is
// not allowed to overwrite an already-applied production transform.
const existingRecords = await readExistingRecords()
const records = { ...existingRecords }
const skipped = []
let applied = 0
for (const [rawFilename, value] of Object.entries(items)) {
  const filename = safeFilename(rawFilename)
  if (!filename) {
    skipped.push(`${rawFilename}: 文件名不安全`)
    continue
  }
  if (!value || typeof value !== 'object') {
    skipped.push(`${filename}: 不是对象`)
    continue
  }
  const candidate = value
  const hasConfirmationMetadata = Object.prototype.hasOwnProperty.call(candidate, 'confirmed')
  const confirmation =
    candidate.confirmed && typeof candidate.confirmed === 'object' ? candidate.confirmed : {}
  // v1 exports did not carry confirmation flags; they represented an already
  // reviewed file and remain supported as a legacy import.  New exports are
  // strict: at least one explicitly confirmed viewport is required.
  const desktopConfirmed = hasConfirmationMetadata ? confirmation.desktop === true : true
  const mobileConfirmed = hasConfirmationMetadata ? confirmation.mobile === true : true
  if (!desktopConfirmed && !mobileConfirmed) {
    skipped.push(`${filename}: 未确认，保留现有生产配置`)
    continue
  }
  const sourcePath = resolve(mediaRoot, filename)
  if (!sourcePath.startsWith(`${mediaRoot}${sep}`)) {
    skipped.push(`${filename}: 文件名越界`)
    continue
  }
  try {
    await access(sourcePath)
  } catch {
    skipped.push(`${filename}: 找不到对应 WebP 素材`)
    continue
  }
  const previous = records[filename]
  records[filename] = {
    filename,
    desktop: desktopConfirmed
      ? normalizeTransform(candidate.desktop)
      : normalizeTransform(previous?.desktop),
    mobile: mobileConfirmed
      ? normalizeTransform(candidate.mobile)
      : normalizeTransform(previous?.mobile),
    schemaVersion,
    ...(typeof candidate.updatedAt === 'string'
      ? { updatedAt: candidate.updatedAt }
      : typeof previous?.updatedAt === 'string'
        ? { updatedAt: previous.updatedAt }
        : {})
  }
  applied += 1
}

const source = `/** Generated by scripts/apply-hero-crops.mjs. Do not edit by hand. */\nimport type { HeroCropRecord } from '@/lib/hero-crop/types'\n\nexport const heroCropSelectionsGenerated: Readonly<Record<string, HeroCropRecord>> = ${JSON.stringify(records, null, 2)}\n`

const preserved = Math.max(0, Object.keys(records).length - applied)
console.log(`可应用 ${applied} 张；保留 ${preserved} 张已有配置；跳过 ${skipped.length} 张。`)
if (skipped.length > 0) skipped.forEach((message) => console.log(`- ${message}`))
if (Object.keys(records).length === 0 && !allowEmpty) {
  console.error('没有可应用的 Hero 记录；为避免误清空现有配置，未写入文件。')
  process.exitCode = 1
  process.exit()
}
if (!dryRun) {
  await writeFile(outputPath, source, 'utf8')
  console.log(`已写入 ${outputPath}`)
} else {
  console.log('dry-run：未写入生产配置。')
}
